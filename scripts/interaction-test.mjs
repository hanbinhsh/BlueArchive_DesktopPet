import { _electron as electron } from 'playwright';
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
const root = path.resolve('.');
const env = { ...process.env, BA_TEST_DATA: path.join(root, 'test-results/interaction-profile') };
delete env.ELECTRON_RUN_AS_NODE;
mkdirSync('test-results', { recursive: true });
mkdirSync(env.BA_TEST_DATA, { recursive: true });
writeFileSync(path.join(env.BA_TEST_DATA, 'settings.json'), JSON.stringify({ character: 'serika', size: 280, yaw: 0, alwaysOnTop: true, position: { x: 600, y: 200 } }));
const app = await electron.launch({ args: ['.'], env });
const checks = [];
try {
  const page = await app.firstWindow();
  await page.waitForFunction(() => window.petDiagnostics?.frames > 5);
  await page.evaluate(() => {
    window.eventLog = [];
    for (const name of ['pointerdown', 'pointermove', 'pointerup', 'lostpointercapture', 'blur']) window.addEventListener(name, e => window.eventLog.push({ name, x: e.screenX, y: e.screenY, cx: e.clientX, cy: e.clientY, shift: e.shiftKey, target: e.target?.id, hit: window.petDiagnostics.hit }));
  });
  await page.mouse.move(210, 180);
  await page.waitForFunction(() => window.petDiagnostics.hit);
  await page.mouse.click(210, 180);
  await page.waitForFunction(() => window.petDiagnostics.action === 'interact');
  await page.waitForTimeout(900);
  await page.screenshot({ path: 'test-results/interaction.png', omitBackground: true });
  await page.waitForFunction(() => window.petDiagnostics.action === 'idle', { timeout: 20000 });
  checks.push('Click plays original reaction and returns to idle');
  await page.mouse.move(10, 10);
  await page.waitForFunction(() => !window.petDiagnostics.hit);
  checks.push('Empty area switches hit state to click-through');
  const old = await page.evaluate(async () => (await window.pet.init()).settings);
  await page.mouse.move(210, 180);
  await page.mouse.wheel(0, -100);
  await page.waitForFunction(async size => (await window.pet.init()).settings.size === size, old.size + 20);
  checks.push('Wheel changes character size');
  await page.waitForTimeout(250);
  await page.keyboard.down('Shift');
  await page.mouse.move(225, 155);
  await page.waitForFunction(() => window.petDiagnostics.hit);
  await page.mouse.down();
  await page.mouse.move(265, 155, { steps: 8 }); await page.mouse.up();
  await page.keyboard.up('Shift');
  const rotated = await page.evaluate(async () => (await window.pet.init()).settings);
  writeFileSync('test-results/pointer-events.json', JSON.stringify(await page.evaluate(() => window.eventLog), null, 2));
  assert.ok(Math.abs(rotated.yaw - old.yaw) > .1);
  assert.equal(await page.evaluate(() => window.petDiagnostics.action), 'idle');
  checks.push('Shift-drag rotates without triggering interaction');
  await app.evaluate(({ BrowserWindow }) => { const win = BrowserWindow.getAllWindows()[0]; win.hide(); win.webContents.send('pet:visibility', false); });
  await page.waitForTimeout(100);
  const paused = await page.evaluate(() => window.petDiagnostics.frames);
  await page.waitForTimeout(1200);
  assert.equal(await page.evaluate(() => window.petDiagnostics.frames), paused);
  await app.evaluate(({ BrowserWindow }) => { const win = BrowserWindow.getAllWindows()[0]; win.showInactive(); win.webContents.send('pet:visibility', true); });
  await page.waitForFunction(count => window.petDiagnostics.frames > count + 10, paused);
  checks.push('Hidden pet pauses rendering; showing it resumes');
  await page.evaluate(() => { window.pet.rotate(0); window.pet.resize(280); });
  writeFileSync('test-results/interactions.json', JSON.stringify({ checks, diagnostics: await page.evaluate(() => window.petDiagnostics) }, null, 2));
  console.log(checks.join('\n'));
} finally { await app.close(); }
