import {extractFile} from '@electron/asar';
import {readFileSync,readdirSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import assert from 'node:assert/strict';
const file='release/v0.1.19/win-unpacked/resources/app.asar';
const matchedBuiltFiles=readdirSync('dist');assert.equal(matchedBuiltFiles.length,7);
for(const name of matchedBuiltFiles)assert.deepEqual(extractFile(file,`dist/${name}`),readFileSync(`dist/${name}`));
const version=JSON.parse(extractFile(file,'package.json')).version;assert.equal(version,'0.1.19');
writeFileSync('test-results/wave8-pack-source.json',JSON.stringify({version,matchedBuiltFiles,appAsarSha256:createHash('sha256').update(readFileSync(file)).digest('hex')},null,2));
console.log('Seven built files match the packaged application');
